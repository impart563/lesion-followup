import assert from "node:assert/strict";
import { resolve, join } from "node:path";
import { pathToFileURL } from "node:url";
const load = name => import(pathToFileURL(join(resolve(process.argv[2]), name)));
const { filterObservationRows: filter, locateObservation: locate } = await load("record-navigation.mjs");
const { invoke, serializeTable } = await load("workbench.mjs");
const { observationForm } = await load("observation-editor.mjs");
const { evaluate } = await load("browser.js");
const { examples } = await load("examples.mjs");
const source = examples.multi;
const model = invoke(evaluate, { action: "editor", ...source }).result;
const before = structuredClone(model);
assert.deepEqual(filter(model), model.rows.map((_, i) => i));
const id = model.rows[0][0];
const selected = filter(model, { visit_id: id, query: "ｔ１" });
assert.deepEqual(selected, [0]);
assert.deepEqual(filter(model, { visit_id: id, query: "T1 2026" }), [0]);
assert.deepEqual(filter(model, { query: "no-such-observation" }), []);
assert.deepEqual(filter(model, { visit_id: "unknown" }), []);
assert.deepEqual(filter(null), []);
const custom = structuredClone(model);
custom.study.targets[0].organ = "合成肺部";
custom.rows[0][4] = "not_evaluable"; custom.rows[0][5] = "";
custom.rows[0][6] = '合成, "Ω"\r\n第二行 😀';
assert.deepEqual(filter(custom, { query: "肺部 无法评价 第二行 Ω 😀" }), [0]);
const sources = serializeTable(custom);
const outputs = () => ["preflight", "review"].map(action => invoke(evaluate, { action, ...sources, format: "json", language: "zh-CN" }));
const reports = outputs();
filter(custom, { query: "no-match" }); filter(custom, { visit_id: id, query: "合成" });
assert.deepEqual(outputs(), reports);
assert.deepEqual(model, before);
assert.deepEqual(locate(model, { source: "followup_csv", visit_id: id, lesion_id: "T1" }), { visit_id: id, lesion_id: "T1" });
assert.equal(locate(model, { visit_id: "unknown" }), null);
assert.equal(locate(model, { visit_id: id, lesion_id: "unknown" }), null);
assert.equal(locate(model, { source: "study_json", visit_id: id }), null);
assert.equal(locate(model, {}), null);
const omitted = structuredClone(model);
omitted.rows.splice(1, 1);
assert.deepEqual(locate(omitted, { visit_id: id, lesion_id: "N1" }), { visit_id: id, lesion_id: "N1" });
assert.equal(observationForm(omitted, id).find(target => target.lesion_id === "N1").state, "missing");
assert.deepEqual(filter(omitted, { query: "未测量" }), omitted.rows.flatMap((row, i) => row[4] === "missing" ? [i] : []));
console.log(JSON.stringify({ search: "passed", navigation: "passed", source_and_report_preservation: "passed", omitted_target: "passed" }));
